import assert from "node:assert/strict";
import {estimatePensionNet,bracketTax,DEFAULT_TAX} from "./app/pension-net.mjs";
const context={dob:"1975-04-14",date:"2026-10-06",type:"fire"};
const near=(a,b)=>assert.ok(Math.abs(a-b)<.011,`${a} != ${b}`);
let n=estimatePensionNet(5348.30,{...DEFAULT_TAX,filing:"joint"},context);
near(n.federal,278.46);near(n.state,128.61);near(n.net,4941.23);
assert.equal(n.fica,0);assert.equal(n.lgers,0);
near(n.net,n.gross-n.federal-n.state);
console.log("Screenshot, married joint, no other income: gross $5,348.30 -> net $"+n.net);
n=estimatePensionNet(5348.30,{...DEFAULT_TAX,filing:"single"},context);
near(n.federal,460.13);near(n.state,171.00);near(n.net,4717.17);
const alone=n.federal;
n=estimatePensionNet(5348.30,{...DEFAULT_TAX,otherIncome:"100000"},context);
assert.ok(n.federal>alone);
n=estimatePensionNet(5348.30,{...DEFAULT_TAX,bailey:true},context);assert.equal(n.state,0);
n=estimatePensionNet(5348.30,{...DEFAULT_TAX,insurance:"500",publicSafety:true,eligiblePremiums:"6000"},context);
const noHelps=estimatePensionNet(5348.30,{...DEFAULT_TAX,insurance:"500"},context);
assert.ok(n.federal<noHelps.federal);assert.ok(n.state<noHelps.state);assert.equal(n.insurance,500);
const general=estimatePensionNet(5348.30,{...DEFAULT_TAX,insurance:"500",publicSafety:true,eligiblePremiums:"6000"},{...context,type:"general"});
assert.equal(general.federal,noHelps.federal);
n=estimatePensionNet(5348.30,{...DEFAULT_TAX,mode:"withholding",federalRate:"10",ncRate:"4.09",insurance:"500",savings:"100"},context);
near(n.federal,534.83);near(n.state,218.75);near(n.net,3994.72);
n=estimatePensionNet(0,{...DEFAULT_TAX,insurance:"500"},context);assert.equal(n.net,0);
n=estimatePensionNet(10,{...DEFAULT_TAX,insurance:"500"},context);assert.equal(n.net,-490);
assert.equal(bracketTax(12400,"single"),1240);assert.equal(bracketTax(50400,"single"),5800);
assert.equal(bracketTax(105700,"head"),16155);assert.equal(bracketTax(384350,"separate"),103291.75);
const senior=estimatePensionNet(5348.30,DEFAULT_TAX,{...context,dob:"1960-04-14"});
assert.ok(senior.federal<alone);
const afterExpiry=estimatePensionNet(5348.30,DEFAULT_TAX,{...context,dob:"1960-04-14",date:"2030-10-06"});
assert.ok(afterExpiry.federal>senior.federal);
const exempt=estimatePensionNet(1000,{...DEFAULT_TAX,taxFreeMonthly:"2000",publicSafety:true,eligiblePremiums:"6000"},context);
assert.equal(exempt.federal,0);assert.equal(exempt.state,0);
n=estimatePensionNet(5348.30,{...DEFAULT_TAX,federalCredits:"100000"},context);assert.equal(n.federal,0);
console.log("Passed bracket boundaries, incremental tax, Bailey, HELPS, FICA/LGERS zero, withholding, premiums, basis, credits and senior expiry.");
